import { Prisma } from '@prisma/client';
import { prisma } from '../config/prisma.js';

export type UserWithDetails = Prisma.UserGetPayload<{
  include: {
    restaurant: true;
    role: {
      include: {
        permissions: {
          include: {
            permission: true;
          };
        };
      };
    };
  };
}>;

export const DUMMY_COST10_HASH = '$2a$10$hfQc6X7MJpyPlpqEcFNP5eGS26kv3eQK/1iGBvPq2oCBqIVHkoY.W';

export class AuthRepository {
  /**
   * Find a user by unique email with active restaurant, role, and permissions
   */
  async findByEmail(email: string): Promise<UserWithDetails | null> {
    return prisma.user.findUnique({
      where: { email },
      include: {
        restaurant: true,
        role: {
          include: {
            permissions: {
              include: {
                permission: true,
              },
            },
          },
        },
      },
    });
  }

  /**
   * Find a user by ID with active restaurant, role, and permissions
   */
  async findById(id: string): Promise<UserWithDetails | null> {
    return prisma.user.findUnique({
      where: { id },
      include: {
        restaurant: true,
        role: {
          include: {
            permissions: {
              include: {
                permission: true,
              },
            },
          },
        },
      },
    });
  }

  /**
   * Verify password using PostgreSQL pgcrypto crypt() against the stored passwordHash
   */
  async verifyPassword(userId: string, plainPassword: string): Promise<boolean> {
    const result = await prisma.$queryRaw<Array<{ is_valid: boolean }>>`
      SELECT (u."passwordHash" = public.crypt(${plainPassword}, u."passwordHash")) AS is_valid
      FROM users u
      WHERE u.id = ${userId}::uuid
    `;
    return Boolean(result[0]?.is_valid);
  }

  /**
   * Dummy verification against a constant cost-10 bcrypt hash to mitigate email-enumeration timing attacks.
   * Matches the cost 10 configuration generated by public.gen_salt('bf', 10).
   */
  async dummyVerifyPassword(plainPassword: string): Promise<boolean> {
    const result = await prisma.$queryRaw<Array<{ is_valid: boolean }>>`
      SELECT (${DUMMY_COST10_HASH} = public.crypt(${plainPassword}, ${DUMMY_COST10_HASH})) AS is_valid
    `;
    return Boolean(result[0]?.is_valid);
  }

  /**
   * Hash a plain password using PostgreSQL pgcrypto BF salt
   */
  async hashPassword(plainPassword: string): Promise<string> {
    const result = await prisma.$queryRaw<Array<{ hash: string }>>`
      SELECT public.crypt(${plainPassword}, public.gen_salt('bf', 10)) AS hash
    `;
    return result[0].hash;
  }

  /**
   * Update the user's last login timestamp
   */
  async updateLastLogin(userId: string): Promise<void> {
    await prisma.user.update({
      where: { id: userId },
      data: { lastLoginAt: new Date() },
    });
  }
}

export const authRepository = new AuthRepository();
