export type LanguageCode = 'en' | 'km' | 'jp';

export function useTranslation() {
  const language = useSettingsStore((s) => s.settings.language) || 'en';
  const t = (key: keyof typeof TRANSLATIONS.en, fallback?: string): string => {
    const lang: LanguageCode = language === 'km' ? 'km' : 'en';
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
    return (dict as any)?.[key] || (TRANSLATIONS.en as any)?.[key] || fallback || (key as string);
  };
  return { t, language };
}
